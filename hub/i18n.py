def translator(lang: str):
    """lang 의 문구 함수. 없는 키는 키 자체를 돌려주어 빠진 문구가 눈에 띄게 한다.

    The string function for lang. A missing key returns the key itself so gaps are visible.
    """
    table = STRINGS.get(lang) or STRINGS["ko"]

    def t(key: str) -> str:
        """키 -> 문구.

        Key -> string.
        """
        return table.get(key, key)

    return t


LANGS = ("ko", "en")
LANG_COOKIE = "hub_lang"


def lang_of(request, default: str) -> str:
    """요청의 화면 언어: ?lang= 이 있으면 그것, 아니면 쿠키, 아니면 설정 기본값. 모르는 값은 무시.

    The request's screen language: ?lang= if present, else the cookie, else the configured default; unknown values ignored.
    """
    for candidate in (request.query_params.get("lang"), request.cookies.get(LANG_COOKIE)):
        if candidate in LANGS:
            return candidate
    return default if default in LANGS else "ko"


THEMES = ("light", "dark", "auto")
THEME_COOKIE = "hub_theme"


def theme_of(request, default: str = "auto") -> str:
    """요청의 화면 테마: ?theme= 이 있으면 그것, 아니면 쿠키, 아니면 기본(auto = OS 설정 따라감). 모르는 값은 무시.

    The request's screen theme: ?theme= if present, else the cookie, else the default (auto follows the OS); unknown ignored.
    """
    for candidate in (request.query_params.get("theme"), request.cookies.get(THEME_COOKIE)):
        if candidate in THEMES:
            return candidate
    return default if default in THEMES else "auto"
